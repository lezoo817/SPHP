"""导诊子图（系分 §5.2.1）。

多轮症状追问 -> RAG 检索 -> 推荐科室 -> 调 query_doctors 查医生 -> 询问挂号/问诊。
绑定导诊场景工具白名单：导诊评估 + 科普检索 + 科室/医生查询 + 健康档案参考。

⚠️ 导诊流程（2026-08-07 对齐原始需求）：
    - **最少两轮对话**：用户首轮描述症状后，Agent 必须追问细节（部位/持续时间/
      体温/过敏史等），不能一上来就调评估工具下结论。
    - **推荐后询问挂号/问诊**：推荐科室与医生后，必须询问用户是否需要继续
      预约挂号或发起在线问诊，不能推荐完就结束。
    软约束由 TRIAGE_SCENE_PROMPT 承担；硬兜底（首轮拦截评估 + 推荐后引导）
    在 tool_caller / reply_node 确定性实现。
"""

from typing import Any

from app.orchestrator.graphs._common import build_tool_subgraph

# 导诊场景工具白名单（系分 §5.2.1 导诊链路）
TRIAGE_TOOLS = [
    "create_triage_assessment",  # 症状导诊评估
    "search_medical_knowledge",  # 医疗科普检索
    "query_departments",  # 科室查询（推荐科室辅助）
    "query_doctors",  # 医生查询（推荐医生）
    "query_health_record",  # 健康档案（导诊参考）
]

# 导诊场景专属指令（系分 §5.11 场景指令，2026-08-07 新增）。
# 对齐原始需求"智能导诊与挂号"：多轮追问 -> 科室推荐 -> 3位医生推荐 -> 询问挂号/问诊。
TRIAGE_SCENE_PROMPT = """【智能导诊场景指令】
当前是智能导诊场景，目标是帮用户找到最合适的科室和医生。按以下流程推进，
一次只推进一个必要步骤，不要一次轮询所有信息。

【多轮症状追问（最少两轮）】
1. 用户首次描述症状后，**不要立即调用导诊评估工具**，先追问症状细节，至少追问
   一轮再评估。可追问的内容：
   - 症状具体部位（如"头痛"是前额/太阳穴/后脑勺）
   - 持续时间与演变（"头疼三天"是持续还是阵发，是否加重）
   - 伴随症状（发烧体温多少、有无恶心呕吐/头晕/视物模糊等）
   - 过敏史与既往病史（可先查用户健康档案 query_health_record 参考）
2. 追问应一次聚焦 1-2 个关键问题，不要一次性抛出全部问题让用户疲劳。

【科室推荐】
3. 症状信息足够（已追问至少一轮）后，调 create_triage_assessment 提交完整症状
   做导诊评估，结合 query_departments 确认推荐科室。向用户说明推荐科室及理由
   （如"头疼伴发热更可能适合神经内科或发热门诊，具体看症状特征"）。
4. **导诊评估只调用一次**：create_triage_assessment 是"提交完整症状评估一次"
   的动作，不要在拿到结果后改写症状描述再次调用（重复评估不会得到更好的科室
   推荐）。若评估返回的推荐科室为空，属于正常情况（评估规则未命中），应改用
   query_departments 查询真实科室列表并向用户说明，不要反复重试评估。
5. 调 query_departments 拿到科室 ID 后，调 query_doctors 查该科室医生。

【医生推荐】
6. 基于医生擅长、号源情况，向用户推荐 **3 位医生**（从 query_doctors 结果中选择，
   不要编造医生），列出姓名、职称、擅长方向，供用户选择。

【询问挂号/问诊】
7. 推荐完科室和医生后，**必须询问用户**："需要我帮您预约挂号，还是发起在线问诊？"
   根据用户选择进入对应流程。不要推荐完就结束。

【边界】
- 不可下诊断结论，不可开方。急危重症症状（胸痛、呼吸困难、剧烈头痛伴呕吐等）
  明确提示立即就医。
- 所有建议标注"AI 建议仅供参考"。"""


def build_triage_graph() -> Any:
    """构造导诊子图（编译后），注入导诊场景指令。"""
    return build_tool_subgraph(
        tool_names=TRIAGE_TOOLS, scene_prompt=TRIAGE_SCENE_PROMPT
    )
